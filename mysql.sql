CREATE DATABASE IF NOT EXISTS ToDoDB;
USE ToDoDB;

CREATE TABLE IF NOT EXISTS items (
  Id INT NOT NULL AUTO_INCREMENT,
  Name VARCHAR(100),
  IsComplete TINYINT(1),
  PRIMARY KEY (Id)
);

CREATE TABLE IF NOT EXISTS users(
    Id INT NOT NULL AUTO_INCREMENT,
    UserName VARCHAR(50),
    Password VARCHAR(30),
    PRIMARY KEY (Id)
);

